# Process diagrams (swimlanes), one notation for every page:
#   lanes  = participants only, always in this order (a diagram uses a subset):
#            Игрок · Мини-приложение · Бот поддержки · Бот команды · Сервер Zerake · Блокчейн · Агент · ClubGG · Команда
#   start  = the event that starts the process        step   = ONE action, in the lane of who does it
#   dec    = ONE check (Да / Нет)                      status = a record changes status (DEP-…, WD-…)
#   end    = the result                                fail   = refusal / exception result      skip = ignored
#   the main path goes down; exceptions go sideways and end in their own result.
# One block = one action or one check, written as a plain sentence. No shorthand, no lists in a block.
# Node: N(id, lane, row, text, kind, col) — col is the sub-column inside a lane listed in "wide".
# Edge: (from, to[, label[, exit side]]).
def N(i, lane, row, text, kind="step", col=0):
    return {"id": i, "lane": lane, "row": row, "text": text, "kind": kind, "col": col}

