# Process diagrams: horizontal swimlanes, one strip per process, at most 8 steps wide so it fits a screen.
#   lanes  = participants (rows), always in this order (a diagram uses a subset):
#            Игрок · Мини-приложение · Бот поддержки · Бот команды · Сервер Zerake · Блокчейн · Агент · ClubGG · Команда
#   start  = the event that starts the process        step   = one action, in the row of who does it
#   dec    = one check (Да / Нет); a "note" under it lists what exactly is checked
#   status = a record changes status (DEP-…, WD-…)    end    = the result
#   fail   = refusal / exception result                skip   = ignored
#   the main path goes left to right; exceptions go up or down to whoever sees them.
# Node: N(id, lane, col, text, kind, sub, note) — sub is the sub-row inside a lane listed in "wide".
# Edge: (from, to[, label[, exit side]]); sides are written as for a top-down flow and turned by the generator.
def N(i, lane, col, text, kind="step", sub=0, note=None):
    return {"id": i, "lane": lane, "row": col, "text": text, "kind": kind, "col": sub, "note": note}

